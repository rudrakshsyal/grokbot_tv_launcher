// Build-time snapshot of "this week" picks: IMDb's public Most Popular charts (MOVIEmeter / TVmeter, which IMDb
// re-ranks weekly from user activity): top 40 of each with IMDb rating, genres, runtime, plot and poster URL, exactly as
// published. No API key needed. The launcher scores this pool into Tonight's Picks and labels it with source + date.
// IMDb's pages sit behind a bot challenge that plain HTTP clients can't pass, so this loads them in headless Chrome.
//   node tools/fetch-weekly.js            -> data/weekly.json + data/weekly.embed.js
// Nothing is invented: if a fetch fails, the old snapshot is kept (or none is written) and the panel stays hidden.
const fs = require('fs'), path = require('path');
let pw; try { pw = require('playwright-core'); } catch (e) { pw = require(process.env.PLAYWRIGHT_CORE || 'playwright-core'); }
const ROOT = path.resolve(__dirname, '..'), N = 40;   // a pool: the launcher scores it down to 3 picks
const CHARTS = { movies: 'https://www.imdb.com/chart/moviemeter/', shows: 'https://www.imdb.com/chart/tvmeter/' };
(async () => {
  const b = await pw.chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome',
    args: ['--disable-blink-features=AutomationControlled'] });
  const ctx = await b.newContext({ locale: 'en-US',
    userAgent: 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36' });
  const p = await ctx.newPage(), out = { source: 'IMDb Most Popular charts', sourceUrl: CHARTS, fetchedAt: new Date().toISOString() };
  try {
    for (const [k, url] of Object.entries(CHARTS)) {
      await p.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
      await p.waitForFunction(() => document.getElementById('__NEXT_DATA__'), null, { timeout: 30000 });
      const nd = JSON.parse(await p.evaluate(() => document.getElementById('__NEXT_DATA__').textContent));
      const edges = nd.props.pageProps.pageData.chartTitles.edges;
      out[k] = edges.slice(0, N).map(e => { const n = e.node, r = n.ratingsSummary || {};
        const img = n.primaryImage && n.primaryImage.url;
        return { imdbId: n.id, title: n.titleText.text, year: (n.releaseYear || {}).year || null, type: (n.titleType || {}).id || null,
          rank: (n.meterRanking || {}).currentRank || null, imdbRating: r.aggregateRating || null, votes: r.voteCount || null,
          genres: ((n.titleGenres || {}).genres || []).map(g => g.genre.text),
          runtimeMin: n.runtime && n.runtime.seconds ? Math.round(n.runtime.seconds / 60) : null,
          plot: n.plot && n.plot.plotText ? n.plot.plotText.plainText : null,
          poster: img ? img.replace(/\._V1_.*\.jpg$/, '._V1_QL75_UX300_.jpg') : null,
          certificate: (n.certificate || {}).rating || null }; });
      if (out[k].length < N) throw new Error(k + ': only ' + out[k].length + ' titles');
    }
  } catch (e) { console.error('fetch failed, keeping previous snapshot:', e.message); await b.close(); process.exit(1); }
  await b.close();
  fs.writeFileSync(path.join(ROOT, 'data', 'weekly.json'), JSON.stringify(out, null, 2) + '\n');
  fs.writeFileSync(path.join(ROOT, 'data', 'weekly.embed.js'), '/* Generated by tools/fetch-weekly.js: real IMDb data, see data/weekly.json */\n' +
    'window.RH_WEEKLY_SNAPSHOT = ' + JSON.stringify(out) + ';\n');
  for (const k of ['shows', 'movies']) out[k].slice(0, 5).forEach(t => console.log(k, t.rank, t.title, t.year, t.imdbRating));
  console.log('fetched', out.fetchedAt);
})();
